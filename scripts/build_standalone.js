/**
 * Build worker/worker.standalone.js from worker/worker.js + assets/cjk_font.bin.
 * The CDN font loader (between @@FONT_LOADER_START / @@FONT_LOADER_END) is
 * replaced with an embedded base64 copy of the font, so the two workers never drift.
 *
 *   node scripts/build_standalone.js --check   # report only, writes nothing
 *   node scripts/build_standalone.js           # write worker/worker.standalone.js
 *   node scripts/build_standalone.js --out x.js  # write somewhere else (for testing)
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "worker", "worker.js");
const FONT = path.join(ROOT, "assets", "cjk_font.bin");
const outIdx = process.argv.indexOf("--out");
const OUT = outIdx > 0 ? path.resolve(process.argv[outIdx + 1]) : path.join(ROOT, "worker", "worker.standalone.js");
const check = process.argv.includes("--check");

const src = fs.readFileSync(SRC, "utf8");
const font = fs.readFileSync(FONT);
const START = "// @@FONT_LOADER_START";
const END = "// @@FONT_LOADER_END";
const a = src.indexOf(START);
const b = src.indexOf(END);
if (a < 0 || b < a) {
  console.error("Font loader markers not found in worker.js");
  process.exit(1);
}

const glyphs = font.length / 9;
const loader = [
  "// Embedded font (" + glyphs + " glyphs): Kana (0x3041..) -> CJK Ideographs (0x4E00..) -> Hangul (0xAC00..)",
  "const CJK_FONT_B64 = \"" + font.toString("base64") + "\";",
  "",
  "let _fontBuf = null;",
  "",
  "async function getFontBuf() {",
  "  if (!_fontBuf) {",
  "    const binStr = atob(CJK_FONT_B64);",
  "    const bytes = new Uint8Array(binStr.length);",
  "    for (let i = 0; i < binStr.length; i++) bytes[i] = binStr.charCodeAt(i);",
  "    _fontBuf = bytes;",
  "  }",
  "  return _fontBuf;",
  "}"
].join("\n");

const header = "// GENERATED by scripts/build_standalone.js from worker/worker.js - do not edit by hand.\n";
const out = header + src.substring(0, a) + loader + src.substring(b + END.length);

const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
console.log("Source:   ", path.relative(ROOT, SRC));
console.log("Font:     ", path.relative(ROOT, FONT), "(" + glyphs + " glyphs, " + (font.length / 1024).toFixed(1) + " KB)");
console.log("Output:   ", path.relative(ROOT, OUT));
console.log("Old size: ", (old.length / 1024).toFixed(1) + " KB", old === out ? "(unchanged)" : "");
console.log("New size: ", (out.length / 1024).toFixed(1) + " KB");

if (check) {
  console.log("\n--check: nothing written.");
} else if (old === out) {
  console.log("\nAlready up to date.");
} else {
  fs.writeFileSync(OUT, out);
  console.log("\nWritten.");
}
